_BASE_YIELD: dict[str, float] = {
    "paddy": 3200, "groundnut": 1500, "sugarcane": 90000,
    "black_gram": 650, "green_gram": 600, "maize": 4500, "ragi": 2200,
}

# Yield noise coefficient (std as fraction of mean)
_YIELD_CV: dict[str, float] = {
    "paddy": 0.18, "groundnut": 0.22, "sugarcane": 0.12,
    "black_gram": 0.25, "green_gram": 0.25, "maize": 0.20, "ragi": 0.20,
}

# Base price (₹/quintal)
_BASE_PRICE: dict[str, float] = {
    "paddy": 1900, "groundnut": 5200, "sugarcane": 3200,
    "black_gram": 6500, "green_gram": 6200, "maize": 1700, "ragi": 2900,
}

# Base cost (₹/ha) per season type
_BASE_COST: dict[str, dict[str, float]] = {
    "paddy":      {"kharif": 38000, "rabi": 36000, "summer": 40000},
    "groundnut":  {"kharif": 25000, "rabi": 23000, "summer": 26000},
    "sugarcane":  {"kharif": 85000, "rabi": 85000, "summer": 85000},
    "black_gram": {"kharif": 18000, "rabi": 17000, "summer": 19000},
    "green_gram": {"kharif": 17000, "rabi": 16000, "summer": 18000},
    "maize":      {"kharif": 22000, "rabi": 21000, "summer": 23000},
    "ragi":       {"kharif": 20000, "rabi": 19000, "summer": 21000},
}

# Rainfall sensitivity of yield (kg/ha per 100 mm above/below seasonal mean)
_YIELD_RAIN_SENSITIVITY: dict[str, float] = {
    "paddy": 150, "groundnut": 80, "sugarcane": 60,
    "black_gram": 50, "green_gram": 50, "maize": 100, "ragi": 70,
}

# Seasonal rainfall parameters (mean_mm, std_mm)
_SEASONAL_RAINFALL: dict[str, tuple[float, float]] = {
    "kharif": (850, 150),
    "rabi":   (280,  80),
    "summer": (120,  50),
}


# ---------------------------------------------------------------------------
# Helper
# ---------------------------------------------------------------------------

def _write_csv(df: pd.DataFrame, path: Path, disclaimer: bool = True) -> None:
    """Write DataFrame to CSV, prepending the synthetic-data disclaimer."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if disclaimer:
        with path.open("w", encoding="utf-8") as fh:
            fh.write(_DISCLAIMER)
            df.to_csv(fh, index=False)
    else:
        df.to_csv(path, index=False)
    logger.info("Wrote synthetic file: %s  (%d rows)", path, len(df))


