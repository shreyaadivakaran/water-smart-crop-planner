# SYNTHETIC DATA MODULE — generates placeholder CSVs for development/testing.
# Output files are NOT real observations. See data/raw/README.txt for schemas.
"""
generate_synthetic.py
---------------------
Generates synthetic raw CSV files for all five data sources used by the
Water-Smart Crop Planner pipeline.

Each dataset is generated only if its ``use_synthetic`` flag is ``true`` in
``config/config.yaml``.  Real files for a given dataset are left untouched.

Usage
-----
    python src/data/generate_synthetic.py              # uses default config
    python src/data/generate_synthetic.py --config config/config.yaml

Output files (when flagged synthetic):
    data/raw/weather.csv
    data/raw/yield.csv
    data/raw/prices.csv
    data/raw/crop_water.csv
    data/raw/cost.csv
"""

